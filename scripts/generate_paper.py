    p(doc, '在性能层面，标准BM25的检索速度约为每查询0.02秒，但将相同的BM25算法直接应用于查询段'
            '（3,000字符、约150-250个独特词元）时，单段检索耗时可达1.7-3.0秒——比标准检索慢85-150倍。'
            '经分析，造成这一显著差异的根本原因在于词元IDF分布的极端差异：完整文档包含大量罕见专业术语'
            '（高IDF，短发布列表），而查询段中占主导的是常见的学术功能词汇（低IDF，长发布列表）。以'
            'max_terms=50为例，分段检索选中的50个查询词的平均发布列表长度可达完整查询的10-50倍，导致单段'
            '遍历数百万发布列表条目。本文采用的三重优化策略（max_df过滤 + max_terms缩减 + heapq.nlargest'
            '替代全排序）将单段检索耗时降至约0.15秒，实现了约20倍的速度提升。')

    heading(doc, '3.3.3 覆盖率加权源投票', level=3)
    p(doc, '将n个查询段独立检索获得的候选源文档列表聚合为最终排序。对于每个候选源文档d，定义其覆盖率'
            '为被多少查询段检索到：count(d) = |{cᵢ : d ∈ Top-50(cᵢ), i = 1, ..., n}|。')
    p(doc, '覆盖率加权BM25得分的计算公式为：\n'
            'Score(d) = Σ_{i=1}^{n} BM25(d|cᵢ) × (1 + count(d) / n)', size=10)
    p(doc, '其中BM25(d|cᵢ)是文档d在查询段cᵢ下的BM25得分（若d不在cᵢ的top-50中，该项为0），n是总查询'
            '段数。覆盖率奖励因子(1 + count(d)/n)的取值范围为[1, 2]，其直观含义是：被多个独立查询段同时'
            '命中的文档获得额外加分——这是"多源一致性"的强信号，表明该文档可能是可疑文档中多个段落的共同'
            '来源，而非仅与某一个段落的某个短语偶然匹配。该投票机制可以视为在构建一个显式的溯源图'
            '（provenance graph）：图的节点为查询段和候选源文档，边表示某个查询段匹配到了某个源文档；'
            '最终排名反映了文档在溯源图中的"全局重要性"——不仅考虑边的权重（BM25得分），还考虑节点的度数'
            '（被多少个段匹配到）。')

    heading(doc, '3.4 性能优化分析', level=2)
    p(doc, '分段检索面临的核心性能瓶颈在于查询段的词元分布特性。令V(q)表示查询q中所有独特词元的集合。'
            '对于完整文档查询，|V(q_full)|通常为数千量级，其中包含大量罕见专业术语（IDF > 5），其发布列表'
            '长度通常仅数十至数百条目。对于查询段c（约3,000字符），|V(c)|通常仅为150-300量级，且大多数'
            '词元为常见的学术功能词汇，其发布列表长度可达30,000至50,000条目（覆盖语料库的50%-83%）。'
            '因此，若不加过滤地遍历top-50查询词的发布列表，单个查询段需执行的打分操作数量为：')
    p(doc, 'S(c) ≈ Σ_{t∈Top-50(c)} |posting(t)| ≈ 50 × 30,000 = 1,500,000', size=10, indent=False)
