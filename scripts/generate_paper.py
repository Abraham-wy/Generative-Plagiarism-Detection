def heading(doc, text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.name = '黑体' if level <= 2 else '宋体'
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '黑体' if level <= 2 else '宋体')


def p(doc, text, bold=False, size=10.5, align=None, indent=True, spacing=3):
    par = doc.add_paragraph()
    if align is not None:
        par.alignment = align
    par.paragraph_format.space_before = Pt(0)
    par.paragraph_format.space_after = Pt(spacing)
    par.paragraph_format.line_spacing = 1.25
    if indent:
        par.paragraph_format.first_line_indent = Cm(0.74)
    run = par.add_run(text)
    run.font.name = '宋体'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    run.font.size = Pt(size)
    run.bold = bold


def add_table(doc, title, headers, rows):
    p(doc, title, size=9, indent=False, bold=True)
    t = doc.add_table(rows=len(rows) + 1, cols=len(headers))
    t.style = 'Table Grid'
    for i, h in enumerate(headers):
        t.rows[0].cells[i].text = h
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            t.rows[r + 1].cells[c].text = val
    p(doc, '', size=4, indent=False)


